/**
 * Explicit QR enrollment, no PIN. Private HTTPS uploads, bounded and resumable
 * by idempotent file/chunk keys. No GPS/VIN, no credentials embedded in APK.
 * Only local T1 files generated by this Receiver can be uploaded.
 */
final class T1CloudDiagnostics {
    interface Callback { void finish(String message,String qrUrl); }
    static final String PREFS="t1_cloud_diagnostics";
    static final String QR_URL="qr_url", STATUS="status", ACTIVE="active";
    private static final String DEVICE="device_id", ENCRYPTED_KEY="device_key";
    private static final String QR_UNTIL="qr_until";
    private static final String KEY_ALIAS="drivelab_auto_diag_qr_keystore_v1";
    private static final String ENDPOINT=
        "https://wgqbvbzhdnkkrpkrohej.supabase.co/functions/v1/drivelab-auto-diagnostics";
    private static final AtomicBoolean UPLOAD_BUSY=new AtomicBoolean(false);
    private static final AtomicBoolean ENROLL_BUSY=new AtomicBoolean(false);
    private static final AtomicBoolean POLL_BUSY=new AtomicBoolean(false);
    private static final SecureRandom RANDOM=new SecureRandom();
    private static final Handler MAIN=new Handler(Looper.getMainLooper());
    private static final int MAX_BYTES=600000, CHUNK_CHARS=4500;

    private T1CloudDiagnostics(){}
    static SharedPreferences prefs(Context c){
        return c.getApplicationContext().getSharedPreferences(PREFS,Context.MODE_PRIVATE);
    }
    private static String hex(byte[] data){
        StringBuilder b=new StringBuilder(data.length*2);
        for(byte c:data)b.append(String.format(Locale.ROOT,"%02x",c&255));
        return b.toString();
    }
    private static String sha(String text)throws Exception{
        return hex(MessageDigest.getInstance("SHA-256").digest(
            text.getBytes(StandardCharsets.UTF_8)));
    }
    private static String randomHex(int bytes){
        byte[] data=new byte[bytes];RANDOM.nextBytes(data);return hex(data);
    }
    private static SecretKey key()throws Exception{
        KeyStore s=KeyStore.getInstance("AndroidKeyStore");
        s.load(null);
        KeyStore.Entry e=s.getEntry(KEY_ALIAS,null);
        if(e instanceof KeyStore.SecretKeyEntry)
            return ((KeyStore.SecretKeyEntry)e).getSecretKey();
        KeyGenerator g=KeyGenerator.getInstance(
            KeyProperties.KEY_ALGORITHM_AES,"AndroidKeyStore");
        g.init(new KeyGenParameterSpec.Builder(KEY_ALIAS,
            KeyProperties.PURPOSE_ENCRYPT|KeyProperties.PURPOSE_DECRYPT)
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            .build());
        return g.generateKey();
    }
    private static String encrypt(String value)throws Exception{
        Cipher c=Cipher.getInstance("AES/GCM/NoPadding");
        c.init(Cipher.ENCRYPT_MODE,key());
        return Base64.encodeToString(c.getIV(),Base64.NO_WRAP)+":"+
            Base64.encodeToString(c.doFinal(value.getBytes(StandardCharsets.UTF_8)),
                Base64.NO_WRAP);
    }
    private static String decrypt(String value)throws Exception{
        String[] x=value.split(":",2);
        if(x.length!=2)throw new IllegalArgumentException("Clave cifrada ausente");
        byte[] iv=Base64.decode(x[0],Base64.NO_WRAP);
        if(iv.length!=12)throw new IllegalArgumentException("IV inválido");
        Cipher c=Cipher.getInstance("AES/GCM/NoPadding");
        c.init(Cipher.DECRYPT_MODE,key(),new GCMParameterSpec(128,iv));
        String secret=new String(c.doFinal(Base64.decode(x[1],Base64.NO_WRAP)),
            StandardCharsets.UTF_8);
        if(!secret.matches("[0-9a-f]{64}"))
            throw new IllegalArgumentException("Clave de dispositivo inválida");
        return secret;
    }
    private static synchronized String[] device(Context app)throws Exception{
        SharedPreferences p=prefs(app);
        String id=p.getString(DEVICE,""),encrypted=p.getString(ENCRYPTED_KEY,"");
        if(!id.isEmpty()&&!encrypted.isEmpty())
            return new String[]{id,decrypt(encrypted)};
        // Store a device-specific 256-bit key encrypted with Android Keystore.
        // A half-written setup must not be treated as an existing device.
        String newId=UUID.randomUUID().toString(),secret=randomHex(32);
        if(!p.edit().putString(DEVICE,newId)
                .putString(ENCRYPTED_KEY,encrypt(secret))
                .putBoolean(ACTIVE,false).commit())
            throw new IllegalStateException("No se pudo guardar el dispositivo");
        return new String[]{newId,secret};
    }
    static String qrUrl(Context c){
        SharedPreferences p=prefs(c);
        return System.currentTimeMillis()<p.getLong(QR_UNTIL,0)?
            p.getString(QR_URL,""):"";
    }
    static boolean active(Context c){return prefs(c).getBoolean(ACTIVE,false);}
    static String status(Context c){
        return prefs(c).getString(STATUS,
            "Nube sin activar · tocá ACTIVAR NUBE CON QR (una sola vez)");
    }
    private static void done(Context app,String message,String qr,Callback callback){
        prefs(app).edit().putString(STATUS,message).apply();
        if(callback!=null)MAIN.post(()->callback.finish(message,qr));
    }
    private static JSONObject request(String action,String id,String secret,
                                      JSONObject data)throws Exception{
        data.put("action",action).put("deviceId",id);
        byte[] bytes=data.toString().getBytes(StandardCharsets.UTF_8);
        HttpURLConnection c=(HttpURLConnection)new URL(ENDPOINT).openConnection();
        try{
            c.setRequestMethod("POST");c.setConnectTimeout(10000);
            c.setReadTimeout(15000);c.setDoOutput(true);
            c.setInstanceFollowRedirects(false);
            c.setRequestProperty("Content-Type","application/json; charset=utf-8");
            if(secret!=null)
                c.setRequestProperty("X-DriveLab-Device-Key",secret);
            c.setFixedLengthStreamingMode(bytes.length);
            try(OutputStream o=c.getOutputStream()){o.write(bytes);}
            int code=c.getResponseCode();
            if(code<200||code>=300)
                throw new IllegalStateException("Servidor HTTP "+code);
            try(InputStream in=c.getInputStream()){
                ByteArrayOutputStream b=new ByteArrayOutputStream();byte[] buf=new byte[2048];
                int n;while((n=in.read(buf))!=-1){
                    if(b.size()+n>8192)throw new IllegalStateException("Respuesta demasiado larga");
                    b.write(buf,0,n);
                }
                JSONObject result=new JSONObject(b.toString("UTF-8"));
                if(!result.optBoolean("ok",false))
                    throw new IllegalStateException("Respuesta sin confirmación");
                return result;
            }
        }finally{c.disconnect();}
    }
    static void beginQr(Context c,Callback callback){
        Context app=c.getApplicationContext();
        if(!ENROLL_BUSY.compareAndSet(false,true)){
            done(app,"Ya hay una activación en curso",qrUrl(app),callback);return;
        }
        new Thread(()->{
            try{
                if(active(app)){
                    done(app,"NUBE ACTIVA · exportación sin PIN",null,callback);return;
                }
                String[] device=device(app);
                String claim=randomHex(24);
                JSONObject body=new JSONObject();
                body.put("authHash",sha(device[1])).put("claim",claim);
                JSONObject response=request("start",device[0],null,body);
                String url=response.getString("url");
                if(!url.startsWith(ENDPOINT+"?claim="))
                    throw new IllegalStateException("URL de QR inválida");
                prefs(app).edit().putString(QR_URL,url)
                    .putLong(QR_UNTIL,System.currentTimeMillis()+300000L).apply();
                done(app,"Escaneá el QR con el Xiaomi. Sin PIN ni códigos.",
                    url,callback);
            }catch(Exception ex){
                done(app,"No se pudo generar QR: "+ex.getClass().getSimpleName()+
                    (ex.getMessage()==null?"":" · "+ex.getMessage()),
                    null,callback);
            }finally{ENROLL_BUSY.set(false);}
        },"T1-Cloud-QR-Create").start();
    }
    static void check(Context c,Callback callback){
        Context app=c.getApplicationContext();
        if(!POLL_BUSY.compareAndSet(false,true))return;
        new Thread(()->{
            try{
                String[] d=device(app);
                JSONObject json=request("status",d[0],d[1],new JSONObject());
                boolean ok=json.optBoolean("active",false);
                prefs(app).edit().putBoolean(ACTIVE,ok).apply();
                if(ok){
                    prefs(app).edit().remove(QR_URL).remove(QR_UNTIL).apply();
                    done(app,"NUBE VINCULADA · ya podés exportar sin PIN",
                        null,callback);
                }else{
                    done(app,"QR pendiente de escaneo desde Xiaomi",
                        qrUrl(app),callback);
                }
            }catch(Exception ex){
                done(app,"No se pudo comprobar nube: "+ex.getClass().getSimpleName()+
                    (ex.getMessage()==null?"":" · "+ex.getMessage()),
                    qrUrl(app),callback);
            }finally{POLL_BUSY.set(false);}
        },"T1-Cloud-QR-Check").start();
    }
    private static byte[] readFile(File source)throws Exception{
        if(!source.isFile()||source.length()<1||source.length()>MAX_BYTES)
            throw new IllegalStateException("CSV inválido o demasiado grande");
        try(InputStream in=new FileInputStream(source)){
            ByteArrayOutputStream out=new ByteArrayOutputStream();
            byte[] buf=new byte[8192];int n;
            while((n=in.read(buf))!=-1){
                if(out.size()+n>MAX_BYTES)
                    throw new IllegalStateException("CSV excede 600 KB");
                out.write(buf,0,n);
            }
            return out.toByteArray();
        }
    }
    static void upload(Context c,File requested,Callback callback){
        Context app=c.getApplicationContext();
        if(!UPLOAD_BUSY.compareAndSet(false,true)){
            done(app,"Otra subida sigue activa",null,callback);return;
        }
        new Thread(()->{
            try{
                if(!active(app)){
                    done(app,"CSV local conservado. Activá la nube con QR una sola vez.",
                        qrUrl(app),callback);return;
                }
                File folder=T1TripRecorderService.tripDir(app).getCanonicalFile();
                File file=requested.getCanonicalFile();
                if(!folder.equals(file.getParentFile())||
                    !file.getName().matches(
                        "(phev_modes|oem_callbacks|code_diag)_[0-9]{8}_[0-9]{6}\\.csv"))
                    throw new IllegalArgumentException("Archivo fuera de carpeta segura");
                byte[] raw=readFile(file);
                String text=new String(raw,StandardCharsets.UTF_8);
                String fileHash=hex(MessageDigest.getInstance("SHA-256").digest(raw));
                String[] d=device(app);
                String fileId=UUID.nameUUIDFromBytes(
                    (d[0]+":"+file.getName()+":"+fileHash).getBytes(StandardCharsets.UTF_8))
                    .toString();
                int total=(text.length()+CHUNK_CHARS-1)/CHUNK_CHARS;
                if(total<1||total>128)
                    throw new IllegalStateException("CSV excede tamaño permitido");
                for(int i=0;i<total;i++){
                    int from=i*CHUNK_CHARS;
                    String chunk=text.substring(from,Math.min(text.length(),from+CHUNK_CHARS));
                    JSONObject body=new JSONObject();
                    body.put("fileId",fileId).put("filename",file.getName())
                        .put("sha256",fileHash).put("chunkIndex",i)
                        .put("chunkTotal",total).put("content",chunk);
                    JSONObject response=request("upload",d[0],d[1],body);
                    if(response.optInt("chunkIndex",-1)!=i||
                        response.optInt("chunkTotal",-1)!=total)
                        throw new IllegalStateException("Recibo de fragmento inválido");
                }
                done(app,"SERVIDOR OK · "+file.getName()+" · "+total+
                    " partes recibidas; CSV local también conservado",null,callback);
            }catch(Exception ex){
                done(app,"CSV LOCAL CONSERVADO · falla de nube: "+
                    ex.getClass().getSimpleName()+
                    (ex.getMessage()==null?"":" · "+ex.getMessage()),
                    null,callback);
            }finally{UPLOAD_BUSY.set(false);}
        },"T1-Cloud-CSV-Upload").start();
    }
}
